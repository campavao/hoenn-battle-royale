#!/usr/bin/env node
// Spike B's shared world, for the relay: web/spike-b/shared/service.ts and everything it
// reads (the Room, sim.ts's walking, world.json, patches.json) in one ES module at
// relay/world/service.js. Railway uploads only relay/, so the bundle is committed;
// `--check` fails when it is not what the source builds now (web's vitest runs it).
//
//   node tools/br/bundle-world.mjs           write it
//   node tools/br/bundle-world.mjs --check   exit 1 if stale
//
// It ends with WORLD_HASH, the sha1 of the rest (see below).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(resolve(root, 'web/package.json'));
const esbuild = require('esbuild');
const out = resolve(root, 'relay/world/service.js');
// The hash again, inside web/: Vercel builds the site from web/ alone, where relay/ is not.
const hashOut = resolve(root, 'web/spike-b/world-hash.json');

const r = await esbuild.build({
  entryPoints: [resolve(root, 'web/spike-b/shared/relay-entry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  write: false,
  legalComments: 'none',
  // the path comments in the output are relative to this: the same from any cwd
  absWorkingDir: root,
  charset: 'utf8',
  banner: { js: '// GENERATED by tools/br/bundle-world.mjs from web/spike-b/shared -- do not edit.' },
});
// What the relay steps, as a hash both ends can compare: the page's build reads it out of
// this file (web/world-hash.ts, in vite.config.ts) and sends it with every join, and a page whose
// world is not this one is told to reload rather than replaying another room (an old tab
// after a deploy).
const body = r.outputFiles[0].text;
const hash = createHash('sha1').update(body).digest('hex').slice(0, 12);
const text = `${body}export const WORLD_HASH = ${JSON.stringify(hash)};\n`;
const hashText = `${JSON.stringify({ hash })}\n`;
if (process.argv.includes('--check')) {
  let now = '', hashNow = '';
  try { now = readFileSync(out, 'utf8'); } catch { /* missing */ }
  try { hashNow = readFileSync(hashOut, 'utf8'); } catch { /* missing */ }
  if (now !== text || hashNow !== hashText) {
    console.error('relay/world/service.js (or web/spike-b/world-hash.json) is stale: run node tools/br/bundle-world.mjs');
    process.exit(1);
  }
  console.log('relay/world/service.js is fresh');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  writeFileSync(hashOut, hashText);
  console.log(`wrote relay/world/service.js (${(text.length / 1024).toFixed(0)} KB)`);
}
